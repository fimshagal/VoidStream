/**
 * Контракт джерела ентропії. Реалізації повертають довільну кількість байтів,
 * які буде влито у внутрішній стан PRNG. Кидайте Error при невдалому виклику —
 * планувальник перейде до наступного джерела наступного циклу.
 */
export interface EntropySource {
    /** Стабільний унікальний ідентифікатор для логування/UI. */
    readonly name: string;
    /** Людиночитна позначка для UI. */
    readonly label: string;
    /** Виконує мережевий запит і повертає сирі байти для змішування. */
    fetch(): Promise<Uint8Array>;
}
